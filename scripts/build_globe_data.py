"""Regenerate the console globe's map data from Natural Earth (public domain) GeoJSON.

    python3 scripts/build_globe_data.py ne_110m_land.geojson ne_50m_admin_0_countries.geojson

Natural Earth v5.1.2, https://github.com/nvkelso/natural-earth-vector/tree/v5.1.2/geojson.
Writes console/src/tui/land.bin, a 720x360 bitmap (half a degree per bit, row 0 at 90N,
column 0 at 180W, most significant bit first) filled by even-odd scanline, and
console/src/tui/centroids.rs, Natural Earth's label point for each ISO 3166-1 alpha-2 code.
"""

from __future__ import annotations

import json
from pathlib import Path
import sys

WIDTH, HEIGHT = 720, 360
TUI = Path(__file__).resolve().parent.parent / "console" / "src" / "tui"


def rings(geometry: dict) -> list[list[tuple[float, float]]]:
    polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
    return [[(x, y) for x, y in ring] for polygon in polygons for ring in polygon]


def land_mask(features: list[dict]) -> bytearray:
    edges = []
    for feature in features:
        for ring in rings(feature["geometry"]):
            edges.extend(zip(ring, ring[1:] + ring[:1]))
    bits = bytearray(WIDTH * HEIGHT // 8)
    for row in range(HEIGHT):
        lat = 90 - (row + 0.5) * 180 / HEIGHT
        crossings = sorted(x1 + (lat - y1) * (x2 - x1) / (y2 - y1)
                           for (x1, y1), (x2, y2) in edges if (y1 > lat) != (y2 > lat))
        for left, right in zip(crossings[::2], crossings[1::2]):
            for col in range(WIDTH):
                if left <= -180 + (col + 0.5) * 360 / WIDTH < right:
                    index = row * WIDTH + col
                    bits[index // 8] |= 0x80 >> (index % 8)
    return bits


def centroids(features: list[dict]) -> dict[str, tuple[float, float]]:
    """A real ISO_A2 wins; ISO_A2_EH fills gaps (France, Norway, Taiwan's "CN-TW") but also
    tags small territories with their parent's code, so it must never override."""
    def code(value: object) -> str | None:
        return value if type(value) is str and len(value) == 2 and value.isalpha() else None

    found: dict[str, tuple[float, float]] = {}
    for key in ("ISO_A2", "ISO_A2_EH"):
        for feature in features:
            props = feature["properties"]
            iso = code(props.get(key))
            if iso and iso not in found:
                found[iso] = (round(props["LABEL_Y"], 1), round(props["LABEL_X"], 1))
    return dict(sorted(found.items()))


def main(land_path: str, countries_path: str) -> None:
    land = json.loads(Path(land_path).read_text())["features"]
    countries = json.loads(Path(countries_path).read_text())["features"]
    (TUI / "land.bin").write_bytes(bytes(land_mask(land)))
    lines = ["// Generated by scripts/build_globe_data.py from Natural Earth v5.1.2 (public domain).",
             "// ISO 3166-1 alpha-2 -> (latitude, longitude) of Natural Earth's label point, sorted.",
             "pub const CENTROIDS: &[(&str, f64, f64)] = &["]
    lines += [f'    ("{code}", {lat:.1f}, {lon:.1f}),' for code, (lat, lon) in centroids(countries).items()]
    lines += ["];", ""]
    (TUI / "centroids.rs").write_text("\n".join(lines))


if __name__ == "__main__":
    main(*sys.argv[1:])
